int main()
{
    const char *english_word = "government";
    const char *hindi_word = "सरकार";

    printf("\n");
    printf("========================================\n");
    printf(" 8-THREAD WORD-SWITCHING BILINGUAL AND\n");
    printf("========================================\n");

    printf("English word : %s\n", english_word);
    printf("Hindi word   : %s\n", hindi_word);

    /*
       --------------------------------------------------------
       Load line index
       --------------------------------------------------------
    */

    long sentence_count = 0;

    LineIndex *index =
        load_line_index(INDEX_FILE,
                        &sentence_count);

    if (!index)
        return 1;

    printf("Sentences    : %ld\n",
           sentence_count);

    /*
       --------------------------------------------------------
       Same 8 byte-balanced partitions
       --------------------------------------------------------
    */

    long starts[NUM_THREADS] = {
        0,
        135438,
        239953,
        444277,
        625648,
        742479,
        848989,
        931634
    };

    long ends[NUM_THREADS] = {
        135437,
        239952,
        444276,
        625647,
        742478,
        848988,
        931633,
        1030874
    };

    /*
       Alternating assignment:

       T0 EN
       T1 HI
       T2 EN
       T3 HI
       T4 EN
       T5 HI
       T6 EN
       T7 HI
    */

    ThreadTask tasks[NUM_THREADS];

    pthread_t threads[NUM_THREADS];

    for (int i = 0;
         i < NUM_THREADS;
         i++) {

        tasks[i].thread_id = i;

        tasks[i].start_id = starts[i];
        tasks[i].end_id = ends[i];

        tasks[i].index = index;

        if (i % 2 == 0) {

            /*
               Phase 1:
               English
            */

            tasks[i].phase1_language = 0;
            tasks[i].word = english_word;

        } else {

            /*
               Phase 1:
               Hindi
            */

            tasks[i].phase1_language = 1;
            tasks[i].word = hindi_word;
        }

        idlist_init(&tasks[i].candidates);
        idlist_init(&tasks[i].final_matches);
    }

    /*
       ========================================================
       PHASE 1
       ========================================================
    */

    printf("\n");
    printf("PHASE 1\n");

    printf("----------------------------------------\n");

    for (int i = 0;
         i < NUM_THREADS;
         i++) {

        printf("T%d: IDs %ld -> %ld | %s | %s\n",
               i,
               tasks[i].start_id,
               tasks[i].end_id,

               tasks[i].phase1_language == 0
                   ? "EN"
                   : "HI",

               tasks[i].word);
    }

    printf("----------------------------------------\n");

    struct timespec total_start;
    struct timespec phase1_start;
    struct timespec phase1_end;
    struct timespec phase2_start;
    struct timespec phase2_end;
    struct timespec total_end;

    clock_gettime(CLOCK_MONOTONIC,
                  &total_start);

    clock_gettime(CLOCK_MONOTONIC,
                  &phase1_start);

    /*
       Create all 8 threads.
    */

    for (int i = 0;
         i < NUM_THREADS;
         i++) {

        int rc =
            pthread_create(&threads[i],
                           NULL,
                           phase1_worker,
                           &tasks[i]);

        if (rc != 0) {

            fprintf(stderr,
                    "pthread_create failed for T%d: %s\n",
                    i,
                    strerror(rc));

            free(index);

            return 1;
        }
    }

    /*
       Wait for all Phase-1 threads.
    */

    for (int i = 0;
         i < NUM_THREADS;
         i++) {

        pthread_join(threads[i], NULL);
    }

    clock_gettime(CLOCK_MONOTONIC,
                  &phase1_end);

    double phase1_time =
        elapsed_seconds(&phase1_start,
                        &phase1_end);

    /*
       Print candidate counts.
    */

    size_t total_candidates = 0;

    for (int i = 0;
         i < NUM_THREADS;
         i++) {

        printf("T%d candidates: %zu\n",
               i,
               tasks[i].candidates.count);

        total_candidates +=
            tasks[i].candidates.count;
    }

    printf("Total candidates: %zu\n",
           total_candidates);

    printf("Phase 1 time: %.6f seconds\n",
           phase1_time);

    /*
       ========================================================
       PHASE 2
       ========================================================

       Each thread stays in its partition and SWITCHES
       to the opposite language/word.
       ========================================================
    */

    printf("\n");
    printf("PHASE 2 - WORD SWITCH\n");

    printf("----------------------------------------\n");

    for (int i = 0;
         i < NUM_THREADS;
         i++) {

        if (tasks[i].phase1_language == 0) {

            printf("T%d: EN -> HI | candidates=%zu\n",
                   i,
                   tasks[i].candidates.count);

        } else {

            printf("T%d: HI -> EN | candidates=%zu\n",
                   i,
                   tasks[i].candidates.count);
        }
    }

    printf("----------------------------------------\n");

    clock_gettime(CLOCK_MONOTONIC,
                  &phase2_start);

    /*
       Important:
       The word must also switch.

       T0/T2/T4/T6:
           phase1 = English word
           phase2 = Hindi word

       T1/T3/T5/T7:
           phase1 = Hindi word
           phase2 = English word
    */

    for (int i = 0;
         i < NUM_THREADS;
         i++) {

        if (tasks[i].phase1_language == 0) {

            tasks[i].word = hindi_word;

        } else {

            tasks[i].word = english_word;
        }
    }

    /*
       Create 8 Phase-2 threads.
    */

    for (int i = 0;
         i < NUM_THREADS;
         i++) {

        int rc =
            pthread_create(&threads[i],
                           NULL,
                           phase2_worker,
                           &tasks[i]);

        if (rc != 0) {

            fprintf(stderr,
                    "pthread_create Phase2 failed "
                    "for T%d: %s\n",
                    i,
                    strerror(rc));

            free(index);

            return 1;
        }
    }

    /*
       Wait for Phase 2.
    */

    for (int i = 0;
         i < NUM_THREADS;
         i++) {

        pthread_join(threads[i], NULL);
    }

    clock_gettime(CLOCK_MONOTONIC,
                  &phase2_end);

    double phase2_time =
        elapsed_seconds(&phase2_start,
                        &phase2_end);

    /*
       ========================================================
       FINAL RESULT
       ========================================================
    */

    size_t total_matches = 0;

    printf("\n");
    printf("FINAL MATCHES\n");

    printf("----------------------------------------\n");

    for (int i = 0;
         i < NUM_THREADS;
         i++) {

        printf("T%d final matches: %zu\n",
               i,
               tasks[i].final_matches.count);

        total_matches +=
            tasks[i].final_matches.count;
    }

    printf("----------------------------------------\n");

    clock_gettime(CLOCK_MONOTONIC,
                  &total_end);

    double total_time =
        elapsed_seconds(&total_start,
                        &total_end);

    printf("Total final matches: %zu\n",
           total_matches);

    printf("\n");
    printf("TIMING\n");
    printf("----------------------------------------\n");

    printf("Phase 1 : %.6f seconds\n",
           phase1_time);

    printf("Phase 2 : %.6f seconds\n",
           phase2_time);

    printf("Total   : %.6f seconds\n",
           total_time);

    /*
       ========================================================
       CLEANUP
       ========================================================
    */

    for (int i = 0;
         i < NUM_THREADS;
         i++) {

        idlist_free(&tasks[i].candidates);
        idlist_free(&tasks[i].final_matches);
    }

    free(index);

    printf("\n");

    return 0;
}