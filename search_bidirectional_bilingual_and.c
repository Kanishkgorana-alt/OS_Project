int is_delimiter(unsigned char c)
{
    return
        c == ' '  ||
        c == '\t' ||
        c == '\r' ||
        c == '\n' ||
        c == '.'  ||
        c == ','  ||
        c == '!'  ||
        c == '?'  ||
        c == ';'  ||
        c == ':'  ||
        c == '"'  ||
        c == '\'' ||
        c == '('  ||
        c == ')'  ||
        c == '['  ||
        c == ']'  ||
        c == '{'  ||
        c == '}'  ||
        c == '<'  ||
        c == '>'  ||
        c == '-'  ||
        c == '/'  ||
        c == '_';
}

/*
   Exact word matching.

   For English:
       case-insensitive.

   For Hindi:
       byte-wise comparison, which is sufficient
       for the exact UTF-8 word used here.
*/
int contains_word(const char *text, const char *word)
{
    size_t word_len = strlen(word);

    if (word_len == 0)
        return 0;

    const char *p = text;

    while (*p) {

        /*
           Find beginning of token.
        */
        while (*p &&
               is_delimiter((unsigned char)*p)) {
            p++;
        }

        if (!*p)
            break;

        const char *start = p;

        /*
           Find end of token.
        */
        while (*p &&
               !is_delimiter((unsigned char)*p)) {
            p++;
        }

        size_t token_len = (size_t)(p - start);

        if (token_len == word_len) {

            int equal = 1;

            for (size_t i = 0; i < word_len; i++) {

                unsigned char a =
                    (unsigned char)start[i];

                unsigned char b =
                    (unsigned char)word[i];

                /*
                   ASCII case-insensitive comparison.
                   Non-ASCII bytes remain unchanged.
                */
                if (a < 128 && b < 128) {
                    a = (unsigned char)tolower(a);
                    b = (unsigned char)tolower(b);
                }

                if (a != b) {
                    equal = 0;
                    break;
                }
            }

            if (equal)
                return 1;
        }
    }

    return 0;
}

/* ============================================================
   LOAD LINE INDEX
   ============================================================ */

LineIndex *load_line_index(const char *filename,
                           long *sentence_count)
{
    FILE *fp = fopen(filename, "r");

    if (!fp) {
        perror("fopen line_index");
        return NULL;
    }

    /*
       First line is:
       id en_offset hi_offset
    */

    char header[256];

    if (!fgets(header, sizeof(header), fp)) {
        fprintf(stderr,
                "ERROR: Could not read index header\n");
        fclose(fp);
        return NULL;
    }

    /*
       Determine number of records.
    */
    long count = 0;

    long id;
    long en_offset;
    long hi_offset;

    while (fscanf(fp,
                  "%ld %ld %ld",
                  &id,
                  &en_offset,
                  &hi_offset) == 3) {

        count++;
    }

    rewind(fp);

    /*
       Skip header again.
    */
    fgets(header, sizeof(header), fp);

    LineIndex *index =
        malloc((size_t)count * sizeof(LineIndex));

    if (!index) {
        fprintf(stderr,
                "ERROR: malloc failed for line index\n");
        fclose(fp);
        return NULL;
    }

    long pos = 0;

    while (pos < count &&
           fscanf(fp,
                  "%ld %ld %ld",
                  &id,
                  &en_offset,
                  &hi_offset) == 3) {

        index[pos].id = id;
        index[pos].en_offset = en_offset;
        index[pos].hi_offset = hi_offset;

        pos++;
    }

    fclose(fp);

    *sentence_count = count;

    return index;
}

/* ============================================================
   GET LINE USING OFFSET
   ============================================================ */

int read_line_at(FILE *fp,
                 long offset,
                 char **line,
                 size_t *capacity)
{
    if (fseek(fp, offset, SEEK_SET) != 0) {
        return 0;
    }

    ssize_t n =
        getline(line, capacity, fp);

    return n >= 0;
}

/* ============================================================
   PHASE 1
   ============================================================ */

void *phase1_worker(void *arg)
{
    ThreadTask *task = (ThreadTask *)arg;

    FILE *fp;

    if (task->phase1_language == 0) {

        fp = fopen(EN_FILE, "rb");

    } else {

        fp = fopen(HI_FILE, "rb");
    }

    if (!fp) {

        fprintf(stderr,
                "Thread %d: cannot open file\n",
                task->thread_id);

        return NULL;
    }

    char *line = NULL;
    size_t capacity = 0;

    for (long id = task->start_id;
         id <= task->end_id;
         id++) {

        long offset;

        if (task->phase1_language == 0)
            offset = task->index[id].en_offset;
        else
            offset = task->index[id].hi_offset;

        if (!read_line_at(fp,
                          offset,
                          &line,
                          &capacity)) {

            fprintf(stderr,
                    "Thread %d: failed reading ID %ld\n",
                    task->thread_id,
                    id);

            continue;
        }

        if (contains_word(line,
                          task->word)) {

            if (!idlist_append(&task->candidates,
                               id)) {

                fprintf(stderr,
                        "Thread %d: candidate append failed\n",
                        task->thread_id);

                break;
            }
        }
    }

    free(line);
    fclose(fp);

    return NULL;
}

/* ============================================================
   PHASE 2
   ============================================================ */

void *phase2_worker(void *arg)
{
    ThreadTask *task = (ThreadTask *)arg;

    /*
       Switch language.
    */
    int phase2_language =
        1 - task->phase1_language;

    FILE *fp;

    if (phase2_language == 0)
        fp = fopen(EN_FILE, "rb");
    else
        fp = fopen(HI_FILE, "rb");

    if (!fp) {

        fprintf(stderr,
                "Thread %d: cannot open phase-2 file\n",
                task->thread_id);

        return NULL;
    }

    char *line = NULL;
    size_t capacity = 0;

    for (size_t i = 0;
         i < task->candidates.count;
         i++) {

        long id = task->candidates.ids[i];

        long offset;

        if (phase2_language == 0)
            offset = task->index[id].en_offset;
        else
            offset = task->index[id].hi_offset;

        if (!read_line_at(fp,
                          offset,
                          &line,
                          &capacity)) {

            fprintf(stderr,
                    "Thread %d: phase-2 read failed for ID %ld\n",
                    task->thread_id,
                    id);

            continue;
        }

        if (contains_word(line,
                          task->word)) {

            if (!idlist_append(&task->final_matches,
                               id)) {

                fprintf(stderr,
                        "Thread %d: final append failed\n",
                        task->thread_id);

                break;
            }
        }
    }

    free(line);
    fclose(fp);

    return NULL;
}

