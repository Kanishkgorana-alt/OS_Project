typedef struct {
    long id;
    long en_offset;
    long hi_offset;
} LineIndex;

typedef struct {
    long *ids;
    size_t count;
    size_t capacity;
} IDList;

typedef struct {
    int thread_id;

    long start_id;
    long end_id;

    const char *word;

    /*
       phase 1:
       0 = English
       1 = Hindi
    */
    int phase1_language;

    /*
       Candidate IDs generated by phase 1.
    */
    IDList candidates;

    /*
       Final matching IDs after phase 2.
    */
    IDList final_matches;

    LineIndex *index;
} ThreadTask;

/* ============================================================
   TIMER
   ============================================================ */

double elapsed_seconds(struct timespec *start,
                       struct timespec *end)
{
    return (double)(end->tv_sec - start->tv_sec)
         + (double)(end->tv_nsec - start->tv_nsec) / 1e9;
}

/* ============================================================
   ID LIST
   ============================================================ */

void idlist_init(IDList *list)
{
    list->ids = NULL;
    list->count = 0;
    list->capacity = 0;
}

int idlist_append(IDList *list, long id)
{
    if (list->count == list->capacity) {

        size_t new_capacity =
            (list->capacity == 0)
            ? 1024
            : list->capacity * 2;

        long *new_ids =
            realloc(list->ids,
                    new_capacity * sizeof(long));

        if (new_ids == NULL) {
            fprintf(stderr,
                    "ERROR: realloc failed while storing ID\n");
            return 0;
        }

        list->ids = new_ids;
        list->capacity = new_capacity;
    }

    list->ids[list->count++] = id;

    return 1;
}

void idlist_free(IDList *list)
{
    free(list->ids);

    list->ids = NULL;
    list->count = 0;
    list->capacity = 0;
}

